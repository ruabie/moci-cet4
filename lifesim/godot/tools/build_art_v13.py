from __future__ import annotations
import math, random, struct, zlib
from pathlib import Path

SIZE=512
ROOT=Path(__file__).resolve().parents[1]/'art'/'interiors_v13'
ROOT.mkdir(parents=True,exist_ok=True)


def png_rgb(path: Path, pixels: bytearray, n: int=SIZE)->None:
    scan=bytearray()
    for y in range(n):
        scan.append(0)
        scan.extend(pixels[y*n*3:(y+1)*n*3])
    def chunk(kind:bytes, data:bytes)->bytes:
        return struct.pack('>I',len(data))+kind+data+struct.pack('>I',zlib.crc32(kind+data)&0xffffffff)
    path.write_bytes(b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',n,n,8,2,0,0,0))+chunk(b'IDAT',zlib.compress(bytes(scan),8))+chunk(b'IEND',b''))


def clamp(x:int)->int: return max(0,min(255,x))


def make(material:str):
    rnd=random.Random('TONGPIN-V13-'+material)
    base=bytearray(SIZE*SIZE*3)
    bumps=bytearray(SIZE*SIZE)
    palette={
        'walnut':(150,117,83),'plaster':(215,205,188),
        'terrazzo':(193,185,170),'linen':(189,176,157)
    }
    palette_base=palette[material]
    # Deterministic mineral grains, wood growth bands and basket-weave fibres.
    # Keep contrast moderate: a real material rather than a disruptive noisy texture.
    wood_streak=[rnd.uniform(-1,1) for _ in range(SIZE)]
    for y in range(SIZE):
        for x in range(SIZE):
            a=rnd.uniform(-1,1)
            if material=='walnut':
                board=y//128
                growth=(math.sin(x*.11+math.sin(y*.016)*1.7)+.5*math.sin(x*.42+y*.021))*4.8
                variation=wood_streak[x]*5+growth+a*3+math.sin(board*3.9)*8
                if y%128<3 or (x%256<2 and board%2==1): variation-=47
                bump=clamp(round(128+growth*1.8+a*2))
                dr=(variation,variation*.83,variation*.65)
            elif material=='plaster':
                weather=math.sin(x*.018+math.cos(y*.017))*2.6 + math.cos(y*.028+x*.006)*2.1
                variation=weather+a*5.0
                bump=clamp(round(128+a*5+weather*.7))
                dr=(variation,variation*.92,variation*.73)
            elif material=='terrazzo':
                fleck=rnd.random()
                mineral = -29 if fleck<.010 else (18 if fleck>.987 else 0)
                margin=-14 if x%96<2 or y%96<2 else 0
                variation=a*3.7+mineral+margin
                bump=clamp(round(128+a*4+mineral*.18+margin*.3))
                dr=(variation,variation*.96,variation*.90)
            else:
                warp=3.5 if x%5==0 else -1.4
                weft=3.4 if y%5==0 else -1.4
                variation=warp+weft+a*3
                bump=clamp(round(128+warp+weft+a*1.8))
                dr=(variation,variation*.91,variation*.83)
            i=(y*SIZE+x)*3
            for c in range(3):base[i+c]=clamp(round(palette_base[c]+dr[c]))
            bumps[y*SIZE+x]=bump
    normals=bytearray(SIZE*SIZE*3)
    for y in range(SIZE):
        for x in range(SIZE):
            l=bumps[y*SIZE+(x-1)%SIZE];r=bumps[y*SIZE+(x+1)%SIZE]
            t=bumps[((y-1)%SIZE)*SIZE+x];b=bumps[((y+1)%SIZE)*SIZE+x]
            nx=(l-r)*.020;ny=(t-b)*.020
            denom=math.sqrt(1+nx*nx+ny*ny)
            i=(y*SIZE+x)*3
            normals[i]=clamp(round((nx/denom*.5+.5)*255))
            normals[i+1]=clamp(round((ny/denom*.5+.5)*255))
            normals[i+2]=clamp(round((1/denom*.5+.5)*255))
    png_rgb(ROOT/f'{material}_base.png',base)
    png_rgb(ROOT/f'{material}_normal.png',normals)
    return (material,len(base))

if __name__=='__main__':
    for material in ('walnut','plaster','terrazzo','linen'):
        print('V13 ART:',make(material))
    print('V13 ART PASS: 4 deterministic PBR finishes and 4 normal maps')